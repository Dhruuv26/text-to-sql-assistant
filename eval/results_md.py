"""Generate docs/RESULTS.md from saved runs.  python -m eval.results_md"""
from __future__ import annotations

from pathlib import Path

from . import analysis
from .stats import wilson_ci

OUT = Path(__file__).resolve().parent.parent / "docs" / "RESULTS.md"
FAIL_COLS = ["wrong_join_or_table", "wrong_aggregation", "wrong_filter", "wrong_output_columns", "wrong_ordering_limit",
             "hallucinated_column", "hallucinated_table", "syntax_error", "db_error_other", "guardrail_blocked", "timeout",
             "other_wrong_result"]


def main_table(group, split):
    sums = analysis.summarize_group(group, split)
    out = ["| Model | Approach | n | Exec. acc. | 95% CI | Easy | Medium | Hard | p50 ms | p95 ms |", "|---|---|---|---|---|---|---|---|---|---|"]
    for k in sorted(group, key=lambda k: (k[0], k[1] != "zero_shot", k[1])):
        s, recs = sums[k], group[k]
        d = s["by_difficulty"]
        lo, hi = wilson_ci(sum(r["correct"] for r in recs), len(recs))

        def g(x, d=d):
            return f"{d[x]['execution_accuracy']}%" if x in d else "-"

        out.append(f"| {k[0]} | {k[1]} | {s['n']} | **{s['execution_accuracy']}%** | {lo}-{hi}% | {g('easy')} | {g('medium')} | {g('hard')} | "
                   f"{s['latency_ms']['p50']:.0f} | {s['latency_ms']['p95']:.0f} |")
    return out


def paired_table(group):
    out = ["| Model | Comparison | Fixed | Broke | p | Verdict |", "|---|---|---|---|---|---|"]
    for model in sorted({k[0] for k in group}):
        base = (model, "zero_shot")
        for k in sorted(group):
            if k[0] == model and k != base and (c := analysis.compare(group, base, k)):
                out.append(f"| {model} | {k[1]} vs zero_shot | {c['fixed']} | {c['broke']} | {c['p']} | {analysis.verdict(c['p'])} |")
        for label, ref, new in analysis.TARGETED:
            if (c := analysis.compare(group, (model, ref), (model, new))):
                out.append(f"| {model} | {new} vs {ref} ({label}) | {c['fixed']} | {c['broke']} | {c['p']} | {analysis.verdict(c['p'])} |")
    return out


def failure_table(group, split):
    sums = analysis.summarize_group(group, split)
    used = [c for c in FAIL_COLS if any(c in s["failures"] for s in sums.values())]
    out = ["| Model | Approach | wrong | " + " | ".join(used) + " |", "|---|---|---|" + "---|" * len(used)]
    for k in sorted(group):
        f = sums[k]["failures"]
        out.append(f"| {k[0]} | {k[1]} | {sum(f.values())} | " + " | ".join(str(f.get(c, 0)) for c in used) + " |")
    return out


def gap_table(dev, test):
    out = ["| Model | Approach | Dev acc. | Test acc. | Gap (pts) |", "|---|---|---|---|---|"]
    for k in sorted(set(dev) & set(test)):
        a = 100 * sum(r["correct"] for r in dev[k]) / len(dev[k])
        b = 100 * sum(r["correct"] for r in test[k]) / len(test[k])
        out.append(f"| {k[0]} | {k[1]} | {a:.1f}% | {b:.1f}% | {a - b:+.1f} |")
    return out


def category_table(group, model):
    keys = [k for k in group if k[0] == model]
    cats = sorted({r["category"] for k in keys for r in group[k]})
    out = ["| Category | n | " + " | ".join(k[1] for k in sorted(keys)) + " |", "|---|---|" + "---|" * len(keys)]
    for c in cats:
        cells, n = [], 0
        for k in sorted(keys):
            rs = [r for r in group[k] if r["category"] == c]
            n = len(rs)
            cells.append(f"{100 * sum(r['correct'] for r in rs) / len(rs):.0f}%" if rs else "-")
        out.append(f"| {c} | {n} | " + " | ".join(cells) + " |")
    return out


def main():
    test, dev, pooled = analysis.load("test"), analysis.load("dev"), analysis.load("pooled")
    if not test:
        raise SystemExit("no test runs found; run `python -m eval.matrix --split test` first")
    lines = ["# Results", "",
             "Generated by `python -m eval.results_md` from the saved runs. Protocol and hypotheses: `eval/PROTOCOL.md`.", "",
             "## Held-out test split (n = 92), the headline numbers", "", *main_table(test, "test"), "",
             "### Paired comparisons (test)", "", *paired_table(test), "",
             "### Failure categories (test; count of wrong answers by first problem found)", "", *failure_table(test, "test"), "",
             "## Dev vs test: optimism of the exploratory split", "", *gap_table(dev, test), ""]
    if pooled:
        lines += ["## Pooled dev + test (n = 143), exploratory", "",
                  "Dev informed the choice of approaches (not their prompts after seeing test), so treat this as a power boost, not a confirmatory test.", "",
                  *main_table(pooled, "pooled"), "", *paired_table(pooled), ""]
    for model in sorted({k[0] for k in test}):
        lines += [f"## Accuracy by question category, test split, {model}", "", *category_table(test, model), ""]
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
